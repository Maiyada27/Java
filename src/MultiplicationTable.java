public class MultiplicationTable {


    public static void main(String[] args) {  /*create main method inside class*/
        int base = 9; /*assign a value for base*/



        for (int i = 1; i <= 10; i++){   /*start a loop from 1 to 10 which is used as a counter*/
           System.out.println(base + "x" + i + "=" + i * base);  /*prints multiplication of base and counter*/

        }

    }
}
